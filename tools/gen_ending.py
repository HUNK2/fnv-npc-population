"""Write the game's "20 years on" scripts from tools/ending_model.py (M4 plan task 4.5).

  mod/company/scripts/CCEndLineFn.gek   one tag's line: the variant the seed picks, its blank filled
  mod/company/scripts/CCEndingFn.gek    the three pages' tags from the ledger, fitted to 200 characters,
                                        appended to the Post as "LETTER day N  20 years on"

The tag order, the variants and the roll (key 40 + the tag's number) come from ending_model.TAGS, so the
game picks the same lines as the model. Run it after any change to the lines:

    python tools/gen_ending.py
"""
from pathlib import Path

import ending_model as em

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'mod' / 'company' / 'scripts'
NAME_FILL = {'town_best': 'town', 'crew_poached': 'person'}


def gek_text(text, fill_kind):
    """A variant as a script expression for sOut."""
    if '%s' not in text:
        return 'let sOut := "%s"' % text
    if fill_kind == 'town':
        return 'let sOut := sv_Construct "%s" sFill' % text.replace('%s', '%z')
    if fill_kind == 'person':
        return 'let sOut := sv_Construct "%s" sFill' % text.replace('%s', '%z')
    return 'let sOut := sv_Construct "%s" iFill' % text.replace('%s', '%.0f')


def line_fn():
    out = ['scn CCEndLineFn', '',
           '; GENERATED by tools/gen_ending.py from tools/ending_model.py TAGS: do not edit by hand.',
           '; The line of tag iTag (ending_model.line): the variant roll(seed, day, 40 + iTag) picks, its blank',
           '; filled with iFill (a number, or for town_best a town index; crew_poached reads CCLate.sPoached).',
           '', 'int iTag', 'int iFill', 'int iDay', 'int iSeed', 'int iV', 'array_var aTN', 'string_var sOut',
           'string_var sFill', '', 'begin Function {iTag iFill}',
           '\tlet iDay := GetVariable "iDay" CCCore',
           '\tlet iSeed := GetVariable "iSeed" CCCore',
           '\tlet aTN := Ar_List "Goodsprings", "Primm", "Sloan", "Mojave Outpost"',
           '\tlet sOut := " "',
           '\tlet iV := ((iDay % 100) * 19 + (iSeed % 100) * 29 + (40 + iTag) * 31) % 100',
           '\tif iTag == %d' % TAG('town_best'),
           '\t\tlet sFill := aTN[iFill]',
           '\telseif iTag == %d' % TAG('crew_poached'),
           '\t\tlet sFill := CCLate.sPoached',
           '\tendif']
    first = True
    for i, (tag, variants) in enumerate(em.TAGS):
        out.append('\t%s iTag == %d' % ('if' if first else 'elseif', i))
        first = False
        out.append('\t\tlet iV := iV %% %d' % len(variants))
        for j, v in enumerate(variants):
            out.append('\t\t%s iV == %d' % ('if' if j == 0 else 'elseif', j))
            out.append('\t\t\t' + gek_text(v, NAME_FILL.get(tag)))
        out.append('\t\tendif')
    out += ['\tendif', '\tSetFunctionValue sOut', 'end', '']
    return '\n'.join(out)


def TAG(name):
    return em.TAG_INDEX[name]


def ending_fn():
    t = TAG
    return '''scn CCEndingFn

; GENERATED by tools/gen_ending.py from tools/ending_model.py (tags): do not edit by hand.
; The three "20 years on" pages (ending_model.tags and fit): each page's tags from the ledger, each
; tag's line from CCEndLineFn, a line left out when it would take the page past 200 characters; the
; pages go to CCCore's Post as "LETTER day N  20 years on" (the caller trims the Post to 3).

int iDay
int iReason
int iPage
int iN
int iK
int iJ
int iBest
array_var aTr
array_var aRun
array_var aT
array_var aF
array_var aX
string_var sPage
string_var sLine
string_var sS

begin Function {}
	let iDay := GetVariable "iDay" CCCore
	let iReason := GetVariable "iEndReason" CCCore
	let aTr := GetArrayVariable "aTrust" CCCore
	set iPage to 0
	while iPage < 3
		let aT := Ar_Construct "array"
		let aF := Ar_Construct "array"
		if iPage == 0
			; how it ended, the towns, the roads
			set iN to iReason
			if iReason == 5
				set iN to 0
			endif
			ar_Append aT iN
			ar_Append aF 0
			let iN := (aTr[0] >= 50) + (aTr[1] >= 50) + (aTr[2] >= 50) + (aTr[3] >= 50)
			if iN >= 2
				ar_Append aT %(towns_many)d
				ar_Append aF iN
			elseif iN == 1
				ar_Append aT %(towns_few)d
				ar_Append aF 1
			else
				ar_Append aT %(towns_none)d
				ar_Append aF 0
			endif
			set iBest to 0
			set iK to 1
			while iK < 4
				if eval (aTr[iK] > aTr[iBest])
					set iBest to iK
				endif
				set iK to iK + 1
			loop
			if eval (aTr[iBest] > 0)
				ar_Append aT %(town_best)d
				ar_Append aF iBest
			endif
			let aRun := call CCRoadsFn 0 iDay
			let iN := (aRun[1] > 0) + (aRun[2] > 0) + (aRun[3] > 0)
			if iN >= 2
				ar_Append aT %(roads_three)d
				ar_Append aF iN
			else
				ar_Append aT %(roads_one)d
				ar_Append aF 0
			endif
		elseif iPage == 1
			; the people, Alice
			let aX := GetArrayVariable "aStaffName" CCCore
			let iN := ar_Size aX
			if iN >= 6
				ar_Append aT %(crew_big)d
				ar_Append aF iN
			else
				if iN < 1
					set iN to 1
				endif
				ar_Append aT %(crew_small)d
				ar_Append aF iN
			endif
			let sS := CCLate.sPoached
			if eval ((sv_Length sS) > 1)
				ar_Append aT %(crew_poached)d
				ar_Append aF 0
			endif
			if eval (GetVariable "iRivalOut" CCLate)
				ar_Append aT %(alice_out)d
			elseif eval ((GetVariable "iAggr" CCLaw) >= 40)
				ar_Append aT %(alice_angry)d
			else
				ar_Append aT %(alice_calm)d
			endif
			ar_Append aF 0
			if eval (GetVariable "iLentEver" CCLate)
				ar_Append aT %(alice_lender)d
				ar_Append aF 0
			endif
		else
			; the NCR, the patron, the loans, the side at the Dam, the close
			if eval (GetVariable "iOutlaw" CCLaw)
				ar_Append aT %(ncr_outlaw)d
			elseif eval ((GetVariable "iStanding" CCLaw) >= 60)
				ar_Append aT %(ncr_good)d
			else
				ar_Append aT %(ncr_plain)d
			endif
			ar_Append aF 0
			let iN := GetVariable "iLaws" CCLate
			if iN > 0
				ar_Append aT %(ncr_laws)d
				ar_Append aF iN
			endif
			if eval (GetVariable "iQm" CCLate)
				ar_Append aT %(patron_kept)d
				ar_Append aF 0
			elseif eval ((GetVariable "iQmOffered" CCLate) && (GetVariable "iQmSince" CCLate))
				ar_Append aT %(patron_broken)d
				ar_Append aF 0
			endif
			let iN := GetVariable "iSeizedN" CCLate
			if iN > 0
				ar_Append aT %(loans_bad)d
				ar_Append aF iN
			endif
			let iN := GetVariable "iSide" CCLate
			if iN >= 1 && iN <= 4
				ar_Append aT (%(side_ncr)d - 1 + iN)
				ar_Append aF 0
			endif
			if iReason == 5
				ar_Append aT %(close_good)d
			else
				ar_Append aT %(close_bad)d
			endif
			ar_Append aF 0
		endif
		; fit the lines to 200 characters (ending_model.fit)
		let sPage := " "
		sv_Erase sPage 0 1
		set iK to 0
		while iK < ar_Size aT
			let iN := aT[iK]
			let iJ := aF[iK]
			let sLine := call CCEndLineFn iN iJ
			if eval ((sv_Length sPage) == 0)
				if eval ((sv_Length sLine) <= 200)
					let sPage := sLine
				endif
			elseif eval ((sv_Length sPage) + 1 + (sv_Length sLine) <= 200)
				let sPage := sPage + " " + sLine
			endif
			set iK to iK + 1
		loop
		let aX := GetArrayVariable "aPostText" CCCore
		ar_Append aX sPage
		let sS := sv_Construct "LETTER day %%.0f  20 years on" iDay
		let aX := GetArrayVariable "aPostTitle" CCCore
		ar_Append aX sS
		set iPage to iPage + 1
	loop
	SetFunctionValue 1
end
''' % {k: t(k) for k in em.TAG_INDEX}


def main():
    (OUT / 'CCEndLineFn.gek').write_text(line_fn(), encoding='utf-8', newline='\n')
    (OUT / 'CCEndingFn.gek').write_text(ending_fn(), encoding='utf-8', newline='\n')
    print('wrote CCEndLineFn.gek and CCEndingFn.gek (%d tags, %d lines)' % (len(em.TAGS), em.line_count()))


if __name__ == '__main__':
    main()
